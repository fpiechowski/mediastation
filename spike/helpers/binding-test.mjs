import { Cdp, getJson } from '../harness/drivers.mjs';
const port = Number(process.argv[2] ?? 9223);
const page = (await getJson(port, '/json/list')).find((t) => t.type === 'page' && !t.url.startsWith('devtools://'));
const cdp = await Cdp.open(page.webSocketDebuggerUrl);
const got = [];
cdp.on('Runtime.bindingCalled', (p) => got.push(p));
const ev = async (e) => (await cdp.send('Runtime.evaluate', { expression: e, returnByValue: true })).result.value;
await cdp.send('Runtime.addBinding', { name: '__msTest' });
console.log('after addBinding, typeof:', await ev('typeof window.__msTest'));
await ev('window.__msTest && window.__msTest("ping")');
await new Promise((r) => setTimeout(r, 300));
console.log('bindingCalled:', got.length, got[0]?.payload);
await cdp.send('Page.enable');
await cdp.send('Page.reload');
await new Promise((r) => setTimeout(r, 4000));
console.log('after reload, typeof:', await ev('typeof window.__msTest'));
await cdp.send('Runtime.addBinding', { name: '__msTest' });
console.log('after re-add, typeof:', await ev('typeof window.__msTest'));
await cdp.send('Runtime.removeBinding', { name: '__msTest' });
cdp.close();
